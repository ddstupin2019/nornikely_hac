import json
from b7_dedup import deduplicate_hypotheses

def main():
    print("=== Тестирование B7: Дедупликация ===")
    
    test_hyps = [
        {
            "название": "Замена ксантогената на дитиофосфат",
            "описание": "Сменить собиратель на дитиофосфат для улучшения селективности.",
            "обоснование": "Короткое обоснование."
        },
        {
            "название": "Уменьшение размера ячеек классификатора",
            "описание": "Уменьшить диаметр насадок до 8мм для лучшего разделения.",
            "обоснование": "Важное обоснование."
        },
        {
            "название": "Использование аэрофлота",
            "описание": "Вместо текущего собирателя применять аэрофлот (дитиофосфат), чтобы селективно извлекать мелкие частицы.",
            "обоснование": "Более длинное и детальное обоснование, так как дитиофосфаты лучше работают со шламами."
        }
    ]
    
    print("\nВходные гипотезы:")
    for i, h in enumerate(test_hyps):
        print(f"{i+1}. {h['название']}")
        
    print("\nЗапуск дедупликации...")
    result = deduplicate_hypotheses(test_hyps)
    
    print("\nОставшиеся уникальные гипотезы:")
    for i, h in enumerate(result):
        print(f"{i+1}. {h['название']}")

if __name__ == "__main__":
    main()
